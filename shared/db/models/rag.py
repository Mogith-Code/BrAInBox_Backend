"""RAG storage: admin-approved source documents and their searchable chunks.

Schema owner: Keshomigha. Used by `ai_service/rag/` (owner: Samni).

`document_chunks` supports hybrid search:
  * `embedding` (pgvector, cosine distance, HNSW index) -> meaning-based search
  * `tsv` (tsvector, GIN index, filled automatically by Postgres) -> exact keyword search
"""

import uuid
from datetime import datetime

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Computed,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from shared.db.base import EMBEDDING_DIM, Base, TimestampMixin, UUIDPrimaryKeyMixin, str_enum
from shared.enums import DocumentStatus, SourceType


class SourceDocument(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """An admin-approved PDF / text (syllabus, teacher's guide...) ingested for RAG."""

    __tablename__ = "source_documents"

    title: Mapped[str] = mapped_column(String(300))
    source_type: Mapped[SourceType] = mapped_column(str_enum(SourceType), index=True)
    file_path: Mapped[str] = mapped_column(String(500), unique=True)
    sha256: Mapped[str | None] = mapped_column(String(64), index=True)  # skip unchanged files
    status: Mapped[DocumentStatus] = mapped_column(
        str_enum(DocumentStatus), default=DocumentStatus.PENDING
    )
    unit_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("units.id", ondelete="SET NULL"), index=True
    )
    year: Mapped[int | None] = mapped_column(Integer)
    page_count: Mapped[int | None] = mapped_column(Integer)
    chunk_count: Mapped[int] = mapped_column(Integer, default=0)
    indexed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    error_message: Mapped[str | None] = mapped_column(Text)
    uploaded_by: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), index=True
    )


class DocumentChunk(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """One searchable piece (a few paragraphs) of a source document."""

    __tablename__ = "document_chunks"
    __table_args__ = (
        UniqueConstraint("document_id", "chunk_index", name="uq_document_chunks_doc_index"),
        # Approximate nearest-neighbour index for cosine similarity.
        Index(
            "ix_document_chunks_embedding_hnsw",
            "embedding",
            postgresql_using="hnsw",
            postgresql_with={"m": 16, "ef_construction": 64},
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
        # Full-text (keyword) index.
        Index("ix_document_chunks_tsv_gin", "tsv", postgresql_using="gin"),
    )

    document_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("source_documents.id", ondelete="CASCADE"), index=True
    )
    chunk_index: Mapped[int] = mapped_column(Integer)  # 0, 1, 2... inside the document
    text: Mapped[str] = mapped_column(Text)
    heading_path: Mapped[str | None] = mapped_column(Text)  # e.g. "Unit 2 > Cell membrane"
    page: Mapped[int | None] = mapped_column(Integer)
    token_count: Mapped[int | None] = mapped_column(Integer)
    unit_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("units.id", ondelete="SET NULL"), index=True
    )
    topic_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("topics.id", ondelete="SET NULL"), index=True
    )
    concept_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("concepts.id", ondelete="SET NULL"), index=True
    )
    # Generated by Postgres from heading + text; never write it yourself.
    tsv: Mapped[str | None] = mapped_column(
        TSVECTOR,
        Computed(
            "to_tsvector('english', coalesce(heading_path, '') || ' ' || text)", persisted=True
        ),
    )
    embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIM))
    embedding_model: Mapped[str | None] = mapped_column(String(64))  # e.g. "gemini-embedding-001"
